-- Категории инструментов
CREATE TABLE tool_categories(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

-- Инструменты
CREATE TABLE development_tools(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    category_id BIGINT NOT NULL,
    description TEXT,
    website_url VARCHAR(500),
    version VARCHAR(50),

    CONSTRAINT fk_tool_category
        FOREIGN KEY (category_id)
            REFERENCES tool_categories(id)
);

-- Языки программирования
CREATE TABLE programming_languages(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

-- Операционные системы
CREATE TABLE operating_systems(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

-- Разработчики
CREATE TABLE developers(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    middle_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(255) NOT NULL UNIQUE,
    specialization VARCHAR(150)
);

-- Программные проекты
CREATE TABLE software_projects(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description TEXT
);

-- Связь проектов и разработчиков
CREATE TABLE project_developers(
    project_id BIGINT NOT NULL,
    developer_id BIGINT NOT NULL,

    PRIMARY KEY (project_id, developer_id),

    FOREIGN KEY (project_id)
        REFERENCES software_projects(id)
        ON DELETE CASCADE,

    FOREIGN KEY (developer_id)
        REFERENCES developers(id)
);

-- Cвязь проектов и операционных систем
CREATE TABLE project_operating_systems(
    project_id BIGINT NOT NULL,
    operating_system_id BIGINT NOT NULL,

    PRIMARY KEY (project_id, operating_system_id),

    FOREIGN KEY (project_id)
        REFERENCES software_projects(id)
        ON DELETE CASCADE,

    FOREIGN KEY (operating_system_id)
        REFERENCES operating_systems(id)
);

-- Связь проектов и языков программирования
CREATE TABLE project_programming_languages(
    project_id BIGINT NOT NULL,
    programming_language_id BIGINT NOT NULL,

    PRIMARY KEY (project_id,programming_language_id),

    FOREIGN KEY (project_id)
        REFERENCES software_projects(id)
        ON DELETE CASCADE,

    FOREIGN KEY (programming_language_id)
        REFERENCES programming_languages(id)
);

--Связь проектов и интстументов
CREATE TABLE project_development_tools(
    project_id BIGINT NOT NULL,
    development_tool_id BIGINT NOT NULL,

    PRIMARY KEY (project_id,development_tool_id),

    FOREIGN KEY (project_id)
        REFERENCES software_projects(id)
        ON DELETE CASCADE,

    FOREIGN KEY (development_tool_id)
        REFERENCES development_tools(id)
);